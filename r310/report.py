"""Roll all evidence up into ../RESULTS.md: one verdict per cycle type (p,k,f)
of an automorphism of prime order p of a hypothetical (3,10,40)-graph."""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RUNS = os.path.join(HERE, "runs")

# Quotient-bound exclusions: (p,k,f) -> independently brute-force audited?
QB = {(7, 1, 33): True, (7, 2, 26): True, (7, 3, 19): False, (5, 1, 35): True,
      (5, 2, 30): True, (5, 3, 25): True, (5, 4, 20): False, (3, 1, 37): True,
      (3, 2, 34): True, (3, 3, 31): True, (2, 1, 38): True, (2, 2, 36): True}


def verified(d):
    a = os.path.join(d, "audit.json")
    if not os.path.exists(a):
        return False
    a = json.load(open(a))
    return a.get("drat_trim") == "VERIFIED" and a.get("lrat_trim") == "VERIFIED"


runs = []
for d in glob.glob(os.path.join(RUNS, "p*_t10_*")):
    sp = os.path.join(d, "summary.json")
    if os.path.exists(sp):
        s = json.load(open(sp))
        if s.get("cube_edges") is None:  # moving-part cubes are superseded by QB
            runs.append((d, s))

cases = []
for p in (7, 5, 3, 2):
    for k in range(40 // p, 0, -1):
        cases.append((p, k, 40 - p * k))

lines = ["# Results: automorphisms of prime order of a hypothetical (3,10,40)-graph", "",
         "Generated by `r310/report.py`. Cycle type: k cycles of length p, f fixed points.",
         "Primes p ≥ 11 are excluded by hand (Theorem A, docs/02).", "",
         "| p | k | f | verdict | evidence |", "| --- | --- | --- | --- | --- |"]
for p, k, f in cases:
    ev, verdict = [], "open"
    if (p, k, f) in QB:
        verdict = "excluded"
        ev.append("quotient bound" + (" (brute-force audited)" if QB[(p, k, f)] else ""))
    mine = [(d, s) for d, s in runs if (s["p"], s["k"], s["f"]) == (p, k, f)]
    whole = [(d, s) for d, s in mine if s.get("nonindep") is None]
    for d, s in whole:
        if s["status"] == "UNSAT":
            verdict = "excluded"
            ev.append(f"SAT UNSAT {s['seconds']}s, {s['cuts']} cuts" +
                      (" — DRAT+LRAT verified" if verified(d) else " — audit pending"))
        elif s["status"] == "WITNESS":
            verdict = "WITNESS"
            ev.append("WITNESS " + s.get("graph6", ""))
    cubes = {}
    for d, s in mine:
        if s.get("nonindep") is not None:
            j = s["nonindep"]
            if s["status"] == "UNSAT" or j not in cubes:
                cubes[j] = (d, s)
    if cubes:
        done = [j for j, (d, s) in cubes.items() if s["status"] == "UNSAT"]
        ver = [j for j in done if verified(cubes[j][0])]
        ev.append(f"invariant cubes j=0..{k}: UNSAT {sorted(done)}, verified {sorted(ver)}")
        if len(done) == k + 1 and verdict == "open":
            verdict = "excluded"
    if verdict == "open" and any(s["status"] == "LIMIT" for d, s in mine):
        ev.append("time limit reached (inconclusive)")
    lines.append(f"| {p} | {k} | {f} | {verdict} | {'; '.join(ev) or '—'} |")
open(os.path.join(HERE, "..", "RESULTS.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
